// Render the actual seeded environments and farm enclosures for visual review.
// No image assets or browser required; the game and Art Studio use these same composers.
// node scripts/environment-gallery.mjs [outdir] [seed]
import fs from 'node:fs';
import path from 'node:path';
import { composeScene } from '../src/visual/env/scene.js';
import { penOf, PEN_KINDS } from '../src/visual/env/pens.js';
import { Pixels } from '../src/visual/pixels.js';
import { encodePng } from './lib/png.mjs';

const out = path.resolve(process.argv[2] || 'test-results/environment-gallery');
const seed = process.argv[3] || 'reference-garden';
const regions = [
  ['meadow', 'Sunlit Meadow'], ['forest', 'Whisperwood'],
  ['netherwood', 'Netherwood'], ['river', 'Willow Bank'],
  ['quarry', 'Ironstone Quarry'], ['moonfen', 'Moonfen'], ['crags', 'Ember Crags'],
];
fs.mkdirSync(out, { recursive: true });

function png(file, pix, scale = 2) {
  const w = pix.w * scale, h = pix.h * scale, rgba = new Uint8Array(w * h * 4);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const c = pix.px[Math.floor(y / scale) * pix.w + Math.floor(x / scale)], k = (y * w + x) * 4;
    rgba[k] = c & 255; rgba[k + 1] = (c >>> 8) & 255; rgba[k + 2] = (c >>> 16) & 255; rgba[k + 3] = c >>> 24;
  }
  fs.writeFileSync(path.join(out, file), encodePng(w, h, rgba));
}

function atlas(items, cellW, cellH) {
  const gap = 4, p = new Pixels(cellW * 2 + gap, Math.ceil(items.length / 2) * (cellH + gap) - gap);
  p.px.fill(0xff19151b);
  items.forEach((pix, i) => p.draw(pix, (i % 2) * (cellW + gap), Math.floor(i / 2) * (cellH + gap)));
  return p;
}

const scenes = [], pens = [], cards = [], timings = [];
for (const [id, title] of regions) {
  const start = performance.now(), sc = composeScene(id, seed);
  timings.push({ region: id, composeMs: Math.round(performance.now() - start), openPixels: sc.open.reduce((a, b) => a + b, 0) });
  scenes.push(sc.pix);
  png(id + '.png', sc.pix);
  cards.push({ file: id + '.png', title });
}
png('wilds-overview.png', atlas(scenes, 384, 216));
const penCards = [];
for (const kind of PEN_KINDS) {
  const p = penOf(kind), pix = new Pixels(p.back.w, p.back.h);
  pix.draw(p.back, 0, 0); pix.draw(p.front, 0, 0);
  pens.push(pix);
  png('pen-' + kind + '.png', pix, 3);
  penCards.push({ file: 'pen-' + kind + '.png', title: p.title });
}
png('enclosures-overview.png', atlas(pens, 224, 92), 3);
const escape = (s) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const section = (title, entries) => `<h2>${title}</h2><div class="grid">${entries.map(({ file, title }) => `<figure><img src="${file}" alt="${title}"><figcaption>${title}</figcaption></figure>`).join('')}</div>`;
fs.writeFileSync(path.join(out, 'index.html'), `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Procedural environment gallery</title>
<style>body{margin:24px;background:#15131b;color:#eee1c9;font:15px monospace}h1{font-size:24px}h2{margin-top:32px}.grid{display:grid;grid-template-columns:repeat(2,minmax(0,1fr));gap:16px}figure{margin:0;background:#231f29;border:1px solid #61503e}img{display:block;width:100%;image-rendering:pixelated}figcaption{padding:10px}p{line-height:1.6}@media(max-width:760px){.grid{grid-template-columns:1fr}}</style>
<h1>Potion Brewer: procedural environments</h1><p>Seed: ${escape(seed)}. Each scene is generated by the game's renderer. Enclosures are shown without animals; their walking and feeding areas remain in the game.</p>
${section('Wilds', cards)}${section('Farm enclosures', penCards)}</html>`);
console.table(timings);
console.log(`Gallery: ${path.join(out, 'index.html')}`);
